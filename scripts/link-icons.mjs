// Copies the link-chip icons out of the icon packages into src/linkIcons.ts,
// so the app ships only the dozen icons it uses. Run: pnpm icons
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const logos = require("@iconify-json/logos/icons.json");
const lucide = require("@iconify-json/lucide/icons.json");
const si = require("simple-icons");

/** Full-color logos from Iconify's "logos" set (CC0). */
const fromLogos = { slack: "slack-icon", gmail: "google-gmail", drive: "google-drive", calendar: "google-calendar", jira: "jira", confluence: "confluence", figma: "figma" };
/** Single-color marks from Simple Icons (CC0), in each brand's color. */
const fromSimple = { docs: si.siGoogledocs, sheets: si.siGooglesheets, slides: si.siGoogleslides };

const svg = (viewBox, body) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}">${body}</svg>`;
const dataUri = (s) => `data:image/svg+xml,${encodeURIComponent(s)}`;

const colored = {};
for (const [kind, name] of Object.entries(fromLogos)) {
  const icon = logos.icons[name];
  colored[kind] = dataUri(svg(`0 0 ${icon.width ?? logos.width} ${icon.height ?? logos.height}`, icon.body));
}
for (const [kind, icon] of Object.entries(fromSimple)) {
  colored[kind] = dataUri(svg("0 0 24 24", `<path fill="#${icon.hex}" d="${icon.path}"/>`));
}

// These follow the text color, so they're drawn inline rather than as images.
const github = logos.icons["github-icon"];
const mono = {
  github: { viewBox: `0 0 ${github.width ?? logos.width} ${github.height ?? logos.height}`, body: github.body.replace(/fill="#[0-9a-f]+"/gi, 'fill="currentColor"') },
  web: { viewBox: "0 0 24 24", body: lucide.icons.globe.body },
};

const out = `// Generated by scripts/link-icons.mjs from @iconify-json/logos, simple-icons and
// @iconify-json/lucide (all CC0). Don't edit by hand; run \`pnpm icons\`.
import type { LinkKind } from "./links";

/** Full-color icons as SVG data URIs. */
export const COLORED_ICONS: Partial<Record<LinkKind, string>> = ${JSON.stringify(colored, null, 2)};

/** Icons drawn in the text color, as inline SVG markup. */
export const MONO_ICONS: Partial<Record<LinkKind, { viewBox: string; body: string }>> = ${JSON.stringify(mono, null, 2)};
`;
writeFileSync(new URL("../src/linkIcons.ts", import.meta.url), out);
console.log("Wrote src/linkIcons.ts");
